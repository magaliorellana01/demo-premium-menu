export function traducirEtiqueta(etiqueta, idioma) {
  if (!etiqueta || idioma === 'es') return etiqueta?.nombre ?? '';
  return ETIQUETAS[etiqueta.clave]?.[idioma] ?? etiqueta.nombre;
}

export function traducirEstadoLocal(texto, idioma) {
  if (!texto || idioma === 'es') return texto;
  let m = texto.match(/^Abierto ahora \u00b7 hasta las (.+)$/);
  if (m) return idioma === 'en' ? `Open now \u00b7 until ${m[1]}` : `\u8425\u4e1a\u4e2d \u00b7 \u8425\u4e1a\u81f3 ${m[1]}`;
  if (texto === 'Abierto ahora') return idioma === 'en' ? 'Open now' : '\u8425\u4e1a\u4e2d';
  m = texto.match(/^Cierra pronto \u00b7 (?:hasta las|a las) (.+)$/);
  if (m) return idioma === 'en' ? `Closing soon \u00b7 closes at ${m[1]}` : `\u5373\u5c06\u6253\u70ca \u00b7 ${m[1]} \u7ed3\u675f`;
  m = texto.match(/^Cerrado \u00b7 abre (hoy|ma\u00f1ana|el pr\u00f3ximo [a-z\u00e1\u00e9\u00ed\u00f3\u00fa]+|el [a-z\u00e1\u00e9\u00ed\u00f3\u00fa]+) a las (.+)$/i);
  if (m) {
    const c = m[1].toLowerCase();
    const h = m[2];
    if (c === 'hoy') return idioma === 'en' ? `Closed \u00b7 opens today at ${h}` : `\u5df2\u6253\u70ca \u00b7 \u4eca\u65e5 ${h} \u8425\u4e1a`;
    if (c === 'ma\u00f1ana') return idioma === 'en' ? `Closed \u00b7 opens tomorrow at ${h}` : `\u5df2\u6253\u70ca \u00b7 \u660e\u65e5 ${h} \u8425\u4e1a`;
    const prox = c.startsWith('el pr\u00f3ximo ');
    const d = DIAS[c.replace(/^el pr\u00f3ximo |^el /, '')]?.[idioma] ?? c;
    return idioma === 'en' ? `Closed \u00b7 opens ${prox ? 'next ' : ''}${d} at ${h}` : `\u5df2\u6253\u70ca \u00b7 ${prox ? '\u4e0b' : ''}${d} ${h} \u8425\u4e1a`;
  }
  if (texto === 'Cerrado') return idioma === 'en' ? 'Closed' : '\u5df2\u6253\u70ca';
  return texto;
}

export function traducirDiaSemana(dia, idioma) {
  if (!dia || idioma === 'es') return dia;
  const nombre = DIAS[dia.nombre.toLowerCase()]?.[idioma] ?? dia.nombre;
  const texto = (dia.cerrado || dia.texto === 'Cerrado')
    ? (idioma === 'en' ? 'Closed' : '\u4f11\u606f')
    : dia.texto.replace(/ a /g, idioma === 'en' ? ' \u2013 ' : ' - ').replace(/ y /g, idioma === 'en' ? ', ' : '\u3001');
  return { ...dia, nombre, texto };
}
